// Generates src/manifest.generated.ts: one entry per shipped face with its byte length
// and `sha256:` content hash, BAKED at authoring time so the runtime never hashes and a
// consumer can pin what it loads. `--check` re-derives and fails on drift, which is the
// CI guard that the recorded hashes always match the shipped bytes.

import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const assetsDir = join(root, 'assets');
const outPath = join(root, 'src', 'manifest.generated.ts');

const files = readdirSync(assetsDir)
  .filter((name) => name.endsWith('.ttf'))
  .sort();

const entries = files.map((name) => {
  const bytes = readFileSync(join(assetsDir, name));
  const hash = `sha256:${createHash('sha256').update(bytes).digest('hex')}`;
  return { file: name, byteLength: bytes.byteLength, hash };
});

const banner =
  '// GENERATED by scripts/generate-manifest.mjs — do not edit.\n' +
  '// Regenerate with `bun run manifest` in packages/fonts; CI verifies via `manifest:check`.\n';

const body =
  banner +
  '\nexport interface FontAssetManifestEntry {\n' +
  '  readonly file: string;\n' +
  '  readonly byteLength: number;\n' +
  '  readonly hash: string;\n' +
  '}\n\n' +
  'export const FONT_ASSET_MANIFEST: readonly FontAssetManifestEntry[] = [\n' +
  entries
    .map(
      (entry) =>
        `  { file: '${entry.file}', byteLength: ${entry.byteLength}, hash: '${entry.hash}' },`
    )
    .join('\n') +
  '\n];\n';

if (process.argv.includes('--check')) {
  // Compare PARSED entries, not raw text: prettier re-wraps the generated file (the
  // repo-wide format script includes it), and a formatting-only difference must not
  // read as hash drift. Only file/byteLength/hash mismatches fail.
  const current = existsSync(outPath) ? readFileSync(outPath, 'utf8') : '';
  const recorded = new Map();
  const entryPattern =
    /file:\s*'([^']+)'\s*,\s*byteLength:\s*(\d+)\s*,\s*hash:\s*'(sha256:[0-9a-f]{64})'/g;
  for (const match of current.matchAll(entryPattern)) {
    recorded.set(match[1], { byteLength: Number(match[2]), hash: match[3] });
  }
  const stale =
    recorded.size !== entries.length ||
    entries.some((entry) => {
      const found = recorded.get(entry.file);
      return !found || found.byteLength !== entry.byteLength || found.hash !== entry.hash;
    });
  if (stale) {
    console.error(
      'packages/fonts manifest is stale: shipped assets do not match src/manifest.generated.ts.\n' +
        'Run `bun run manifest` in packages/fonts (then `bun run format`) and commit the result.'
    );
    process.exit(1);
  }
  console.log(`fonts manifest OK (${entries.length} faces)`);
} else {
  writeFileSync(outPath, body);
  console.log(`wrote ${outPath} (${entries.length} faces)`);
}
