/** A pattern fill: the tile's foreground rows and the two colours. @public */
export interface VectorPattern {
  /** Eight rows of foreground cells from the top; the leftmost cell is the high bit. */
  readonly rows: readonly number[];
  readonly foreground: ShapeColor;
  readonly background: ShapeColor;
}

const BLACK: ShapeColor = { hex: '000000', alpha: 1 };
const WHITE: ShapeColor = { hex: 'FFFFFF', alpha: 1 };

function colorOf(
  pattFill: OoxmlElement,
  name: 'fgClr' | 'bgClr',
  resolveSchemeColor: ShapeSchemeColorResolver | undefined,
  placeholder: ShapeColor | undefined
): ShapeColor | null | undefined {
  const holder = findDirectChild(pattFill.children, { namespaceUri: A, localName: name });
  if (!holder) return undefined;
  const node = holder.children.find(isElement);
  return node ? resolveColorNode(node, resolveSchemeColor, placeholder) : undefined;
}

/**
 * The pattern an `a:pattFill` paints, or null when its preset is unknown or a colour does not
 * resolve. A missing foreground is black and a missing background white.
 */
export function readPatternFill(
  pattFill: OoxmlElement,
  resolveSchemeColor?: ShapeSchemeColorResolver,
  placeholder?: ShapeColor
): VectorPattern | null {
  const rows = PATTERN_ROWS.get(schemaAttributeValue(pattFill.attributes, 'prst') ?? 'pct5');
  if (!rows) return null;
  const foreground = colorOf(pattFill, 'fgClr', resolveSchemeColor, placeholder);
  const background = colorOf(pattFill, 'bgClr', resolveSchemeColor, placeholder);
  if (foreground === null || background === null) return null;
  return { rows, foreground: foreground ?? BLACK, background: background ?? WHITE };
}

const FILL_NAMES = new Set(['noFill', 'solidFill', 'gradFill', 'blipFill', 'pattFill', 'grpFill']);

/** The pattern of `parent` when an `a:pattFill` is the element that fills it. */
export function authoredPatternFill(
  parent: OoxmlElement,
  resolveSchemeColor?: ShapeSchemeColorResolver
): VectorPattern | null {
  for (const node of parent.children) {
    if (!isElement(node) || node.namespaceUri !== A || !FILL_NAMES.has(node.localName)) continue;
    return node.localName === 'pattFill' ? readPatternFill(node, resolveSchemeColor) : null;
  }
  return null;
}

/** The colour a pattern averages to, for outputs that paint one colour. */
export function patternMeanColor(pattern: VectorPattern): ShapeColor {
  let cells = 0;
  for (const row of pattern.rows) {
    for (let bit = 0; bit < 8; bit += 1) cells += (row >> bit) & 1;
  }
  const share = cells / 64;
  const channel = (hex: string, at: number) => Number.parseInt(hex.slice(at, at + 2), 16);
  const mix = (at: number) =>
    Math.round(
      channel(pattern.foreground.hex, at) * share +
        channel(pattern.background.hex, at) * (1 - share)
    )
      .toString(16)
      .padStart(2, '0')
      .toUpperCase();
  return {
    hex: `${mix(0)}${mix(2)}${mix(4)}`,
    alpha: pattern.foreground.alpha * share + pattern.background.alpha * (1 - share),
  };
}
